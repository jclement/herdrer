package review

import (
	"bytes"
	"html"
	"strings"

	"github.com/alecthomas/chroma/v2"
	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/lexers"
	"github.com/alecthomas/chroma/v2/styles"
)

// maxHighlightBytes bounds what we will tokenise.
//
// Highlighting is linear but not free, and a review document can carry a very
// large diff. Past this size the reader is scrolling, not reading, and a slow
// render on a phone is worse than plain text.
const maxHighlightBytes = 256 * 1024

// highlightStyles: one per theme. The document already knows which it is, so
// only the chosen stylesheet is emitted rather than both plus a selector.
const (
	styleLight = "github"
	styleDark  = "github-dark"
)

// highlight renders source as syntax-highlighted HTML.
//
// It returns escaped plain text when the language is unknown or the input is
// too large, so an unrecognised language degrades to readable code rather than
// to an error. The output is generated by chroma from the source text, which it
// escapes itself — the caller must not run it through the markdown sanitiser,
// which would strip the class attributes the stylesheet depends on.
func highlight(source, lang string, dark bool) (out string, highlighted bool) {
	if len(source) > maxHighlightBytes {
		return html.EscapeString(source), false
	}

	lexer := lexerFor(lang)
	if lexer == nil {
		return html.EscapeString(source), false
	}
	lexer = chroma.Coalesce(lexer)

	style := styles.Get(styleLight)
	if dark {
		style = styles.Get(styleDark)
	}
	if style == nil {
		style = styles.Fallback
	}

	// Classes, not inline styles: a 300-line diff with a style attribute on
	// every span is enormous, and the document already carries a stylesheet.
	formatter := chromahtml.New(
		chromahtml.WithClasses(true),
		chromahtml.PreventSurroundingPre(true),
	)

	iterator, err := lexer.Tokenise(nil, source)
	if err != nil {
		return html.EscapeString(source), false
	}
	var buf bytes.Buffer
	if err := formatter.Format(&buf, style, iterator); err != nil {
		return html.EscapeString(source), false
	}
	return buf.String(), true
}

// lexerFor resolves a language name, trying the name the author gave before
// falling back to chroma's own alias matching.
func lexerFor(lang string) chroma.Lexer {
	lang = strings.TrimSpace(strings.ToLower(lang))
	if lang == "" {
		return nil
	}
	// A few names authors reach for that chroma spells differently.
	switch lang {
	case "cs", "c#", "dotnet":
		lang = "csharp"
	case "ts", "tsx":
		lang = "typescript"
	case "js", "jsx", "mjs", "cjs":
		lang = "javascript"
	case "ex", "exs":
		lang = "elixir"
	case "sh", "shell", "zsh", "console":
		lang = "bash"
	case "yml":
		lang = "yaml"
	case "golang":
		lang = "go"
	case "text", "txt", "plain", "plaintext":
		return nil
	}
	return lexers.Get(lang)
}

// highlightCSS returns the stylesheet for the chosen theme.
func highlightCSS(dark bool) string {
	name := styleLight
	if dark {
		name = styleDark
	}
	style := styles.Get(name)
	if style == nil {
		style = styles.Fallback
	}
	formatter := chromahtml.New(chromahtml.WithClasses(true))
	var buf bytes.Buffer
	if err := formatter.WriteCSS(&buf, style); err != nil {
		return ""
	}
	return buf.String()
}
